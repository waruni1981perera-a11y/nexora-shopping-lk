-- IMPORTANT: Admin users are granted manually by the project owner. Never expose a service_role key in frontend code.

create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'General',
  description text,
  price numeric(12,2) not null check (price >= 0),
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null,
  phone text not null,
  email text not null,
  delivery_address text not null,
  payment_method text not null,
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'Pending' check (status in ('Pending','Confirmed','Processing','Shipped','Delivered','Cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  created_at timestamptz not null default now()
);

create or replace function public.is_nexora_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.admin_users where user_id = auth.uid()); $$;

alter table public.products enable row level security;
alter table public.admin_users enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.messages enable row level security;

-- Public visitors can read active products. Only admin accounts can manage products.
drop policy if exists "Anyone can read active products" on public.products;
create policy "Anyone can read active products" on public.products for select using (active = true or public.is_nexora_admin());
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all to authenticated using (public.is_nexora_admin()) with check (public.is_nexora_admin());

-- A signed-in user can see only their own admin marker. No client insert/update/delete policy.
drop policy if exists "Users can see own admin marker" on public.admin_users;
create policy "Users can see own admin marker" on public.admin_users for select to authenticated using (user_id = auth.uid());

-- Customers create and read their own orders; admins can read and update all orders.
drop policy if exists "Customers create own orders" on public.orders;
create policy "Customers create own orders" on public.orders for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Customers read own orders" on public.orders;
create policy "Customers read own orders" on public.orders for select to authenticated using (user_id = auth.uid() or public.is_nexora_admin());
drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update to authenticated using (public.is_nexora_admin()) with check (public.is_nexora_admin());

-- Order items can be inserted/read only when the related order belongs to the signed-in user, or user is admin.
drop policy if exists "Customers add own order items" on public.order_items;
create policy "Customers add own order items" on public.order_items for insert to authenticated with check (
  exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid())
  or public.is_nexora_admin()
);
drop policy if exists "Customers read own order items" on public.order_items;
create policy "Customers read own order items" on public.order_items for select to authenticated using (
  exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid())
  or public.is_nexora_admin()
);

-- Anyone can submit a support message; only admins can read messages.
drop policy if exists "Visitors can send messages" on public.messages;
create policy "Visitors can send messages" on public.messages for insert to anon, authenticated with check (char_length(message) between 1 and 4000);
drop policy if exists "Admins read messages" on public.messages;
create policy "Admins read messages" on public.messages for select to authenticated using (public.is_nexora_admin());

